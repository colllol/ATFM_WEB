-- Read metadata, then exercise isolated notification fixtures inside one
-- transaction that is ALWAYS rolled back. Do not call legacy commit wrappers.
DECLARE
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_COUNT FROM USER_OBJECTS
    WHERE OBJECT_NAME IN ('T_AI_RECIPIENT_MAP', 'T_AI_NOTIFICATION_SYNC',
        'AI_NOTIFICATION_PKG', 'NOTIFICATION_PKG')
      AND STATUS = 'VALID';
    IF V_COUNT <> 6 THEN RAISE_APPLICATION_ERROR(-20147, 'Expected 6 valid notification integration objects.'); END IF;
    FOR R IN (SELECT NAME, TYPE, LINE, POSITION, TEXT FROM USER_ERRORS
              WHERE NAME IN ('AI_NOTIFICATION_PKG', 'NOTIFICATION_PKG')
              ORDER BY NAME, TYPE, SEQUENCE) LOOP
        DBMS_OUTPUT.PUT_LINE(R.NAME || ' ' || R.TYPE || ' ' || R.LINE || ':' || R.POSITION || ' ' || R.TEXT);
    END LOOP;
    FOR R IN (SELECT SOURCE_NAME, LAST_ID, AUDIENCE_MODE FROM T_AI_NOTIFICATION_SYNC) LOOP
        DBMS_OUTPUT.PUT_LINE(R.SOURCE_NAME || ': last_id=' || R.LAST_ID || ', audience=' || R.AUDIENCE_MODE);
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('PASS 6 valid schema objects.');
END;
