PROMPT === ACCEPT NONEXISTENT ID (EXPECTED 0) ===
DECLARE
    v_missing_id NUMBER;
    v_returncode NUMBER;
BEGIN
    SELECT NVL(MAX(FLIGHT_ID), 0) + 1000000
      INTO v_missing_id
      FROM T_CANCELED_FLIGHTS;

    CANCELED_STATUS_PKG.ACCEPT_CANCELED_FLIGHTS(
        P_FLIGHT_IDS => TO_CHAR(v_missing_id),
        P_USER       => 'CODEX_VERIFY',
        P_RETURNCODE => v_returncode
    );

    DBMS_OUTPUT.PUT_LINE('P_RETURNCODE=' || TO_CHAR(v_returncode));
END;
