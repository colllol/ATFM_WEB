PROMPT === COLUMN / STATUS COUNTS ===
SELECT COLUMN_NAME, DATA_TYPE, DATA_DEFAULT, NULLABLE
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME = 'T_CANCELED_FLIGHTS'
   AND COLUMN_NAME = 'ISACCEPTED';

SELECT ISACCEPTED, COUNT(*) AS ROW_COUNT
  FROM T_CANCELED_FLIGHTS
 GROUP BY ISACCEPTED
 ORDER BY ISACCEPTED;

PROMPT === INDEX / PACKAGE STATUS ===
SELECT INDEX_NAME, STATUS, VISIBILITY
  FROM USER_INDEXES
 WHERE TABLE_NAME = 'T_CANCELED_FLIGHTS'
   AND INDEX_NAME = 'IX_TCAN_STATUS_DATE';

SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN
       (
           'CANCELED_STATUS_PKG',
           'CANCEL_FLIGHTS_PKG',
           'FINISH_FLIGHTS_PKG'
       )
 ORDER BY OBJECT_NAME, OBJECT_TYPE;

SELECT TYPE, LINE, POSITION, TEXT
  FROM USER_ERRORS
 WHERE NAME IN
       (
           'CANCELED_STATUS_PKG',
           'CANCEL_FLIGHTS_PKG',
           'FINISH_FLIGHTS_PKG'
       )
 ORDER BY NAME, SEQUENCE;

