CREATE OR REPLACE PACKAGE AI_NOTIFICATION_PKG AS
    TYPE T_CURSOR IS REF CURSOR;
    FUNCTION CAN_RECEIVE(P_RECIPIENT_ID IN VARCHAR2, P_USER_ID IN NUMBER) RETURN NUMBER;
    PROCEDURE GET_STATE(P_USER_ID IN NUMBER, P_OUT_CURSOR OUT T_CURSOR);
    PROCEDURE GET_PAGE(P_USER_ID IN NUMBER, P_STATUS IN NUMBER,
        P_PAGE_INDEX IN NUMBER, P_PAGE_SIZE IN NUMBER, P_SOURCE_TYPE IN VARCHAR2,
        P_DATA_CURSOR OUT T_CURSOR, P_TOTAL_CURSOR OUT T_CURSOR);
    PROCEDURE MARK_READ(P_USER_ID IN NUMBER, P_ID IN NUMBER, P_UPDATED_COUNT OUT NUMBER);
    PROCEDURE MARK_ALL_READ(P_USER_ID IN NUMBER, P_SOURCE_TYPE IN VARCHAR2,
        P_UPDATED_COUNT OUT NUMBER);
    PROCEDURE RECONCILE_TARGETS;
END AI_NOTIFICATION_PKG;
/

CREATE OR REPLACE PACKAGE BODY AI_NOTIFICATION_PKG AS
    FUNCTION CAN_RECEIVE(P_RECIPIENT_ID IN VARCHAR2, P_USER_ID IN NUMBER) RETURN NUMBER IS
        V_COUNT NUMBER;
        V_USER_ID NUMBER;
        V_MODE VARCHAR2(20);
        V_RECIPIENT T_AI_RECIPIENT_MAP.RECIPIENT_ID%TYPE;
    BEGIN
        SELECT COUNT(*) INTO V_COUNT FROM T_USERS
        WHERE USERID = P_USER_ID AND USERID > 0 AND USERACTIVE = 1;
        IF V_COUNT = 0 THEN RETURN 0; END IF;
        BEGIN
            SELECT AUDIENCE_MODE INTO V_MODE FROM T_AI_NOTIFICATION_SYNC WHERE SOURCE_NAME = 'NL2SQL';
        EXCEPTION WHEN NO_DATA_FOUND THEN RETURN 0;
        END;
        IF V_MODE = 'ALL_USERS' THEN RETURN 1; END IF;
        IF V_MODE <> 'MAPPED' OR P_RECIPIENT_ID IS NULL THEN RETURN 0; END IF;
        V_RECIPIENT := CASE WHEN INSTR(P_RECIPIENT_ID, '@') > 0
            THEN LOWER(TRIM(P_RECIPIENT_ID)) ELSE P_RECIPIENT_ID END;
        SELECT COUNT(*) INTO V_COUNT FROM T_AI_RECIPIENT_MAP WHERE RECIPIENT_ID = V_RECIPIENT;
        IF V_COUNT > 0 THEN
            SELECT COUNT(*) INTO V_COUNT FROM T_AI_RECIPIENT_MAP
            WHERE RECIPIENT_ID = V_RECIPIENT AND USER_ID = P_USER_ID AND IS_ACTIVE = 1;
            RETURN CASE WHEN V_COUNT > 0 THEN 1 ELSE 0 END;
        END IF;
        IF INSTR(V_RECIPIENT, '@') = 0 THEN RETURN 0; END IF;
        SELECT COUNT(*), MIN(USERID) INTO V_COUNT, V_USER_ID FROM T_USERS
        WHERE USERACTIVE = 1 AND USERID > 0 AND LOWER(TRIM(USEREMAIL)) = V_RECIPIENT;
        RETURN CASE WHEN V_COUNT = 1 AND V_USER_ID = P_USER_ID THEN 1 ELSE 0 END;
    END CAN_RECEIVE;

    PROCEDURE VALIDATE_USER(P_USER_ID IN NUMBER) IS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*) INTO V_COUNT FROM T_USERS
        WHERE USERID = P_USER_ID AND USERID > 0 AND USERACTIVE = 1;
        IF V_COUNT = 0 THEN RAISE_APPLICATION_ERROR(-20141, 'Active USER_ID is required.'); END IF;
    END;

    FUNCTION NORMALIZE_SOURCE(P_SOURCE_TYPE IN VARCHAR2) RETURN VARCHAR2 IS
        V_SOURCE VARCHAR2(30) := NVL(UPPER(TRIM(P_SOURCE_TYPE)), 'ALL');
    BEGIN
        IF V_SOURCE = 'AI_QUERY' THEN V_SOURCE := 'AI'; END IF;
        IF V_SOURCE NOT IN ('ALL', 'AI') THEN
            RAISE_APPLICATION_ERROR(-20142, 'Unsupported notification source filter.');
        END IF;
        RETURN V_SOURCE;
    END;

    PROCEDURE GET_STATE(P_USER_ID IN NUMBER, P_OUT_CURSOR OUT T_CURSOR) IS
    BEGIN
        VALIDATE_USER(P_USER_ID);
        OPEN P_OUT_CURSOR FOR
            SELECT ID, TITLE, CONTENT, DATETIME, SOURCE_TYPE, SOURCE_KEY,
                   AI_RECIPIENT_ID, STATUS, UNREAD_COUNT, AI_UNREAD_COUNT
            FROM (
                SELECT V.*, COUNT(*) OVER () UNREAD_COUNT,
                       SUM(CASE WHEN SOURCE_TYPE = 'AI' THEN 1 ELSE 0 END) OVER () AI_UNREAD_COUNT
                FROM (
                    SELECT N.ID, N.TITLE, N.CONTENT, N.DATETIME, N.SOURCE_TYPE, N.SOURCE_KEY,
                           N.AI_RECIPIENT_ID, P_USER_ID USER_ID,
                           CASE WHEN R.NOTIFICATION_ID IS NULL THEN 0 ELSE 1 END STATUS
                    FROM T_NOTIFICATION N
                    LEFT JOIN T_NOTIFICATION_READ R ON R.NOTIFICATION_ID = N.ID AND R.USER_ID = P_USER_ID
                    WHERE (N.TARGET_TYPE = 0 OR EXISTS (SELECT 1 FROM T_NOTIFICATION_TARGET T
                               WHERE T.NOTIFICATION_ID = N.ID AND T.USER_ID = P_USER_ID))
                      AND (NVL(N.SOURCE_TYPE, '~') <> 'AI'
                           OR (N.TARGET_TYPE = 1 AND AI_NOTIFICATION_PKG.CAN_RECEIVE(N.AI_RECIPIENT_ID, P_USER_ID) = 1))
                ) V
                WHERE USER_ID = P_USER_ID AND STATUS = 0
                ORDER BY DATETIME DESC, ID DESC
            ) WHERE ROWNUM <= 50;
    END;

    PROCEDURE GET_PAGE(P_USER_ID IN NUMBER, P_STATUS IN NUMBER,
        P_PAGE_INDEX IN NUMBER, P_PAGE_SIZE IN NUMBER, P_SOURCE_TYPE IN VARCHAR2,
        P_DATA_CURSOR OUT T_CURSOR, P_TOTAL_CURSOR OUT T_CURSOR) IS
        V_SOURCE VARCHAR2(30) := NORMALIZE_SOURCE(P_SOURCE_TYPE);
        V_STATUS NUMBER := CASE WHEN P_STATUS IN (0, 1) THEN P_STATUS ELSE -1 END;
        V_PAGE_INDEX NUMBER := GREATEST(TRUNC(NVL(P_PAGE_INDEX, 1)), 1);
        V_PAGE_SIZE NUMBER := LEAST(GREATEST(TRUNC(NVL(P_PAGE_SIZE, 100)), 1), 100);
    BEGIN
        VALIDATE_USER(P_USER_ID);
        OPEN P_DATA_CURSOR FOR
            SELECT ID, TITLE, CONTENT, DATETIME, SOURCE_TYPE, SOURCE_KEY, AI_RECIPIENT_ID, STATUS
            FROM (
                SELECT V.*, ROW_NUMBER() OVER (ORDER BY DATETIME DESC, ID DESC) ROW_NUMBER_VALUE
                FROM (
                    SELECT N.ID, N.TITLE, N.CONTENT, N.DATETIME, N.SOURCE_TYPE, N.SOURCE_KEY,
                           N.AI_RECIPIENT_ID, P_USER_ID USER_ID,
                           CASE WHEN R.NOTIFICATION_ID IS NULL THEN 0 ELSE 1 END STATUS
                    FROM T_NOTIFICATION N
                    LEFT JOIN T_NOTIFICATION_READ R ON R.NOTIFICATION_ID = N.ID AND R.USER_ID = P_USER_ID
                    WHERE (N.TARGET_TYPE = 0 OR EXISTS (SELECT 1 FROM T_NOTIFICATION_TARGET T
                               WHERE T.NOTIFICATION_ID = N.ID AND T.USER_ID = P_USER_ID))
                      AND (NVL(N.SOURCE_TYPE, '~') <> 'AI'
                           OR (N.TARGET_TYPE = 1 AND AI_NOTIFICATION_PKG.CAN_RECEIVE(N.AI_RECIPIENT_ID, P_USER_ID) = 1))
                ) V
                WHERE USER_ID = P_USER_ID AND (V_STATUS = -1 OR STATUS = V_STATUS)
                  AND (V_SOURCE = 'ALL' OR SOURCE_TYPE = V_SOURCE)
            ) WHERE ROW_NUMBER_VALUE BETWEEN ((V_PAGE_INDEX - 1) * V_PAGE_SIZE) + 1 AND V_PAGE_INDEX * V_PAGE_SIZE
            ORDER BY ROW_NUMBER_VALUE;
        OPEN P_TOTAL_CURSOR FOR
            SELECT COUNT(CASE WHEN (V_STATUS = -1 OR STATUS = V_STATUS)
                               AND (V_SOURCE = 'ALL' OR SOURCE_TYPE = V_SOURCE) THEN 1 END) TOTAL_COUNT,
                   COUNT(CASE WHEN STATUS = 0 THEN 1 END) UNREAD_COUNT,
                   COUNT(CASE WHEN STATUS = 0 AND SOURCE_TYPE = 'AI' THEN 1 END) AI_UNREAD_COUNT
            FROM (
                    SELECT N.ID, N.TITLE, N.CONTENT, N.DATETIME, N.SOURCE_TYPE, N.SOURCE_KEY,
                           N.AI_RECIPIENT_ID, P_USER_ID USER_ID,
                           CASE WHEN R.NOTIFICATION_ID IS NULL THEN 0 ELSE 1 END STATUS
                    FROM T_NOTIFICATION N
                    LEFT JOIN T_NOTIFICATION_READ R ON R.NOTIFICATION_ID = N.ID AND R.USER_ID = P_USER_ID
                    WHERE (N.TARGET_TYPE = 0 OR EXISTS (SELECT 1 FROM T_NOTIFICATION_TARGET T
                               WHERE T.NOTIFICATION_ID = N.ID AND T.USER_ID = P_USER_ID))
                      AND (NVL(N.SOURCE_TYPE, '~') <> 'AI'
                           OR (N.TARGET_TYPE = 1 AND AI_NOTIFICATION_PKG.CAN_RECEIVE(N.AI_RECIPIENT_ID, P_USER_ID) = 1))
                ) WHERE USER_ID = P_USER_ID;
    END;

    PROCEDURE MARK_READ(P_USER_ID IN NUMBER, P_ID IN NUMBER, P_UPDATED_COUNT OUT NUMBER) IS
    BEGIN
        VALIDATE_USER(P_USER_ID);
        INSERT INTO T_NOTIFICATION_READ (NOTIFICATION_ID, USER_ID)
        SELECT ID, P_USER_ID FROM (
                    SELECT N.ID, N.TITLE, N.CONTENT, N.DATETIME, N.SOURCE_TYPE, N.SOURCE_KEY,
                           N.AI_RECIPIENT_ID, P_USER_ID USER_ID,
                           CASE WHEN R.NOTIFICATION_ID IS NULL THEN 0 ELSE 1 END STATUS
                    FROM T_NOTIFICATION N
                    LEFT JOIN T_NOTIFICATION_READ R ON R.NOTIFICATION_ID = N.ID AND R.USER_ID = P_USER_ID
                    WHERE (N.TARGET_TYPE = 0 OR EXISTS (SELECT 1 FROM T_NOTIFICATION_TARGET T
                               WHERE T.NOTIFICATION_ID = N.ID AND T.USER_ID = P_USER_ID))
                      AND (NVL(N.SOURCE_TYPE, '~') <> 'AI'
                           OR (N.TARGET_TYPE = 1 AND AI_NOTIFICATION_PKG.CAN_RECEIVE(N.AI_RECIPIENT_ID, P_USER_ID) = 1))
                )
        WHERE USER_ID = P_USER_ID AND ID = P_ID AND STATUS = 0;
        P_UPDATED_COUNT := SQL%ROWCOUNT;
    EXCEPTION WHEN DUP_VAL_ON_INDEX THEN P_UPDATED_COUNT := 0;
    END;

    PROCEDURE MARK_ALL_READ(P_USER_ID IN NUMBER, P_SOURCE_TYPE IN VARCHAR2,
        P_UPDATED_COUNT OUT NUMBER) IS
        V_SOURCE VARCHAR2(30) := NORMALIZE_SOURCE(P_SOURCE_TYPE);
    BEGIN
        VALIDATE_USER(P_USER_ID);
        -- Ignore concurrent inserts by another request for this same user.
        INSERT /*+ IGNORE_ROW_ON_DUPKEY_INDEX(T_NOTIFICATION_READ PK_T_NOTIFICATION_READ) */
        INTO T_NOTIFICATION_READ (NOTIFICATION_ID, USER_ID)
        SELECT ID, P_USER_ID FROM (
                    SELECT N.ID, N.TITLE, N.CONTENT, N.DATETIME, N.SOURCE_TYPE, N.SOURCE_KEY,
                           N.AI_RECIPIENT_ID, P_USER_ID USER_ID,
                           CASE WHEN R.NOTIFICATION_ID IS NULL THEN 0 ELSE 1 END STATUS
                    FROM T_NOTIFICATION N
                    LEFT JOIN T_NOTIFICATION_READ R ON R.NOTIFICATION_ID = N.ID AND R.USER_ID = P_USER_ID
                    WHERE (N.TARGET_TYPE = 0 OR EXISTS (SELECT 1 FROM T_NOTIFICATION_TARGET T
                               WHERE T.NOTIFICATION_ID = N.ID AND T.USER_ID = P_USER_ID))
                      AND (NVL(N.SOURCE_TYPE, '~') <> 'AI'
                           OR (N.TARGET_TYPE = 1 AND AI_NOTIFICATION_PKG.CAN_RECEIVE(N.AI_RECIPIENT_ID, P_USER_ID) = 1))
                )
        WHERE USER_ID = P_USER_ID AND STATUS = 0 AND (V_SOURCE = 'ALL' OR SOURCE_TYPE = V_SOURCE);
        P_UPDATED_COUNT := SQL%ROWCOUNT;
    END;

    PROCEDURE RECONCILE_TARGETS IS
    BEGIN
        UPDATE T_NOTIFICATION SET TARGET_TYPE = 1 WHERE SOURCE_TYPE = 'AI' AND TARGET_TYPE <> 1;
        DELETE FROM T_NOTIFICATION_TARGET T
        WHERE EXISTS (SELECT 1 FROM T_NOTIFICATION N WHERE N.ID = T.NOTIFICATION_ID AND N.SOURCE_TYPE = 'AI')
          AND EXISTS (SELECT 1 FROM T_NOTIFICATION N WHERE N.ID = T.NOTIFICATION_ID
                      AND AI_NOTIFICATION_PKG.CAN_RECEIVE(N.AI_RECIPIENT_ID, T.USER_ID) = 0);
        INSERT /*+ IGNORE_ROW_ON_DUPKEY_INDEX(T_NOTIFICATION_TARGET PK_T_NOTIFICATION_TARGET) */
        INTO T_NOTIFICATION_TARGET (NOTIFICATION_ID, USER_ID)
        SELECT N.ID, U.USERID FROM T_NOTIFICATION N
        CROSS JOIN (SELECT DISTINCT USERID FROM T_USERS WHERE USERACTIVE = 1 AND USERID > 0) U
        WHERE N.SOURCE_TYPE = 'AI'
          AND AI_NOTIFICATION_PKG.CAN_RECEIVE(N.AI_RECIPIENT_ID, U.USERID) = 1
          AND NOT EXISTS (SELECT 1 FROM T_NOTIFICATION_TARGET T
                          WHERE T.NOTIFICATION_ID = N.ID AND T.USER_ID = U.USERID);
    END;
END AI_NOTIFICATION_PKG;
