-- Preserve the old API signatures and commit behavior while closing stale AI
-- visibility through legacy callers. CREATE_NOTIFICATION remains local-only.
CREATE OR REPLACE PACKAGE BODY NOTIFICATION_PKG AS
    PROCEDURE GET_STATE(P_USER_ID IN NUMBER, P_OUT_CURSOR OUT T_CURSOR) IS
    BEGIN AI_NOTIFICATION_PKG.GET_STATE(P_USER_ID, P_OUT_CURSOR); END;

    PROCEDURE GET_PAGE(P_USER_ID IN NUMBER, P_STATUS IN NUMBER,
        P_PAGE_INDEX IN NUMBER, P_PAGE_SIZE IN NUMBER,
        P_DATA_CURSOR OUT T_CURSOR, P_TOTAL_CURSOR OUT T_CURSOR) IS
    BEGIN
        AI_NOTIFICATION_PKG.GET_PAGE(P_USER_ID, P_STATUS, P_PAGE_INDEX, P_PAGE_SIZE,
            'ALL', P_DATA_CURSOR, P_TOTAL_CURSOR);
    END;

    PROCEDURE MARK_READ(P_USER_ID IN NUMBER, P_ID IN NUMBER, P_UPDATED_COUNT OUT NUMBER) IS
    BEGIN AI_NOTIFICATION_PKG.MARK_READ(P_USER_ID, P_ID, P_UPDATED_COUNT); COMMIT; END;

    PROCEDURE MARK_ALL_READ(P_USER_ID IN NUMBER, P_UPDATED_COUNT OUT NUMBER) IS
    BEGIN AI_NOTIFICATION_PKG.MARK_ALL_READ(P_USER_ID, 'ALL', P_UPDATED_COUNT); COMMIT; END;

    PROCEDURE CREATE_NOTIFICATION(P_TITLE IN NVARCHAR2, P_CONTENT IN NVARCHAR2,
        P_USER_IDS IN VARCHAR2, P_ID OUT NUMBER) IS
        V_TARGET_TYPE NUMBER(1);
    BEGIN
        IF TRIM(P_TITLE) IS NULL OR TRIM(P_CONTENT) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20002, 'TITLE and CONTENT are required.');
        END IF;
        V_TARGET_TYPE := CASE WHEN TRIM(P_USER_IDS) IS NULL THEN 0 ELSE 1 END;
        INSERT INTO T_NOTIFICATION (TITLE, CONTENT, DATETIME, TARGET_TYPE)
        VALUES (TRIM(P_TITLE), TRIM(P_CONTENT), SYSTIMESTAMP, V_TARGET_TYPE) RETURNING ID INTO P_ID;
        IF V_TARGET_TYPE = 1 THEN
            INSERT INTO T_NOTIFICATION_TARGET (NOTIFICATION_ID, USER_ID)
            SELECT P_ID, USER_ID FROM (
                SELECT DISTINCT TO_NUMBER(TRIM(REGEXP_SUBSTR(P_USER_IDS, '[^,]+', 1, LEVEL))) USER_ID
                FROM DUAL CONNECT BY REGEXP_SUBSTR(P_USER_IDS, '[^,]+', 1, LEVEL) IS NOT NULL
            ) WHERE USER_ID > 0;
            IF SQL%ROWCOUNT = 0 THEN
                RAISE_APPLICATION_ERROR(-20003, 'At least one target USER_ID is required.');
            END IF;
        END IF;
        COMMIT;
    EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
    END;
END NOTIFICATION_PKG;
