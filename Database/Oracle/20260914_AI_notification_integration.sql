-- T_USERS.USERID has no unique constraint on existing installations; avoid
-- adding a foreign key that cannot compile or modifying legacy user ownership.
-- Both explicit and automatic mappings require an active user at read time.
BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE T_AI_NOTIFICATION_SYNC (
        SOURCE_NAME VARCHAR2(30 CHAR) NOT NULL,
        LAST_ID NUMBER(19) DEFAULT 0 NOT NULL,
        LAST_POLL_AT TIMESTAMP NULL,
        AUDIENCE_MODE VARCHAR2(20 CHAR) DEFAULT ''ALL_USERS'' NOT NULL,
        CONSTRAINT PK_T_AI_NOTIFICATION_SYNC PRIMARY KEY (SOURCE_NAME),
        CONSTRAINT CK_AI_NOTIFICATION_SYNC_ID CHECK (LAST_ID >= 0),
        CONSTRAINT CK_AI_NOTIFICATION_AUDIENCE CHECK (AUDIENCE_MODE IN (''ALL_USERS'', ''MAPPED'')))';
EXCEPTION WHEN OTHERS THEN IF SQLCODE <> -955 THEN RAISE; END IF;
END;
