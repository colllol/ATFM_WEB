-- Seed only once: rerunning a migration must not rewind an established cursor.
BEGIN
    MERGE INTO T_AI_NOTIFICATION_SYNC D
    USING (SELECT 'NL2SQL' SOURCE_NAME FROM DUAL) S ON (S.SOURCE_NAME = D.SOURCE_NAME)
    WHEN NOT MATCHED THEN INSERT (SOURCE_NAME, LAST_ID, LAST_POLL_AT, AUDIENCE_MODE)
    VALUES (S.SOURCE_NAME, 0, NULL, 'ALL_USERS');
    COMMIT;
END;
