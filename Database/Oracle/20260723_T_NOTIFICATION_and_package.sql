CREATE OR REPLACE PACKAGE NOTIFICATION_PKG AS
    TYPE T_CURSOR IS REF CURSOR;

    PROCEDURE GET_STATE(P_OUT_CURSOR OUT T_CURSOR);
    PROCEDURE GET_PAGE(
        P_STATUS IN NUMBER,
        P_PAGE_INDEX IN NUMBER,
        P_PAGE_SIZE IN NUMBER,
        P_DATA_CURSOR OUT T_CURSOR,
        P_TOTAL_CURSOR OUT T_CURSOR);
    PROCEDURE MARK_READ(P_ID IN NUMBER, P_UPDATED_COUNT OUT NUMBER);
    PROCEDURE MARK_ALL_READ(P_UPDATED_COUNT OUT NUMBER);
END NOTIFICATION_PKG;
/

CREATE OR REPLACE PACKAGE BODY NOTIFICATION_PKG AS
    PROCEDURE GET_STATE(P_OUT_CURSOR OUT T_CURSOR) IS
    BEGIN
        OPEN P_OUT_CURSOR FOR
            SELECT RECENT.ID,
                   RECENT.TITLE,
                   RECENT.CONTENT,
                   RECENT.DATETIME,
                   RECENT.STATUS,
                   RECENT.UNREAD_COUNT
            FROM (
                SELECT ID,
                       TITLE,
                       CONTENT,
                       DATETIME,
                       STATUS,
                       COUNT(*) OVER () AS UNREAD_COUNT
                FROM T_NOTIFICATION
                WHERE STATUS = 0
                ORDER BY DATETIME DESC, ID DESC
            ) RECENT
            WHERE ROWNUM <= 50;
    END GET_STATE;

    PROCEDURE GET_PAGE(
        P_STATUS IN NUMBER,
        P_PAGE_INDEX IN NUMBER,
        P_PAGE_SIZE IN NUMBER,
        P_DATA_CURSOR OUT T_CURSOR,
        P_TOTAL_CURSOR OUT T_CURSOR) IS
        V_STATUS NUMBER := CASE WHEN P_STATUS IN (0, 1) THEN P_STATUS ELSE -1 END;
        V_PAGE_INDEX NUMBER := GREATEST(NVL(P_PAGE_INDEX, 1), 1);
        V_PAGE_SIZE NUMBER := LEAST(GREATEST(NVL(P_PAGE_SIZE, 100), 1), 100);
        V_FIRST_ROW NUMBER;
        V_LAST_ROW NUMBER;
    BEGIN
        V_FIRST_ROW := ((V_PAGE_INDEX - 1) * V_PAGE_SIZE) + 1;
        V_LAST_ROW := V_PAGE_INDEX * V_PAGE_SIZE;

        OPEN P_DATA_CURSOR FOR
            SELECT PAGE_DATA.ID,
                   PAGE_DATA.TITLE,
                   PAGE_DATA.CONTENT,
                   PAGE_DATA.DATETIME,
                   PAGE_DATA.STATUS
            FROM (
                SELECT N.ID,
                       N.TITLE,
                       N.CONTENT,
                       N.DATETIME,
                       N.STATUS,
                       ROW_NUMBER() OVER (ORDER BY N.DATETIME DESC, N.ID DESC) AS ROW_NUMBER_VALUE
                FROM T_NOTIFICATION N
                WHERE V_STATUS = -1 OR N.STATUS = V_STATUS
            ) PAGE_DATA
            WHERE PAGE_DATA.ROW_NUMBER_VALUE BETWEEN V_FIRST_ROW AND V_LAST_ROW
            ORDER BY PAGE_DATA.ROW_NUMBER_VALUE;

        OPEN P_TOTAL_CURSOR FOR
            SELECT (SELECT COUNT(*)
                    FROM T_NOTIFICATION N
                    WHERE V_STATUS = -1 OR N.STATUS = V_STATUS) AS TOTAL_COUNT,
                   (SELECT COUNT(*)
                    FROM T_NOTIFICATION
                    WHERE STATUS = 0) AS UNREAD_COUNT
            FROM DUAL;
    END GET_PAGE;

    PROCEDURE MARK_READ(P_ID IN NUMBER, P_UPDATED_COUNT OUT NUMBER) IS
    BEGIN
        UPDATE T_NOTIFICATION
        SET STATUS = 1
        WHERE ID = P_ID
          AND STATUS = 0;
        P_UPDATED_COUNT := SQL%ROWCOUNT;
        COMMIT;
    END MARK_READ;

    PROCEDURE MARK_ALL_READ(P_UPDATED_COUNT OUT NUMBER) IS
    BEGIN
        UPDATE T_NOTIFICATION
        SET STATUS = 1
        WHERE STATUS = 0;
        P_UPDATED_COUNT := SQL%ROWCOUNT;
        COMMIT;
    END MARK_ALL_READ;
END NOTIFICATION_PKG;
