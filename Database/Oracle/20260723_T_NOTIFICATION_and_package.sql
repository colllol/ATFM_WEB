BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE T_NOTIFICATION (
            ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
            TITLE NVARCHAR2(250) NOT NULL,
            CONTENT NVARCHAR2(2000) NOT NULL,
            DATETIME TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            STATUS NUMBER(1) DEFAULT 0 NOT NULL,
            CONSTRAINT CK_T_NOTIFICATION_STATUS CHECK (STATUS IN (0, 1))
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE INDEX IX_T_NOTIFICATION_STATE_TIME
        ON T_NOTIFICATION (STATUS, DATETIME DESC, ID DESC)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

CREATE OR REPLACE PACKAGE NOTIFICATION_PKG AS
    TYPE T_CURSOR IS REF CURSOR;

    PROCEDURE GET_STATE(P_OUT_CURSOR OUT T_CURSOR);
    PROCEDURE MARK_ALL_READ(P_UPDATED_COUNT OUT NUMBER);
END NOTIFICATION_PKG;
/

CREATE OR REPLACE PACKAGE BODY NOTIFICATION_PKG AS
    PROCEDURE GET_STATE(P_OUT_CURSOR OUT T_CURSOR) IS
    BEGIN
        OPEN P_OUT_CURSOR FOR
            SELECT RECENT.ID,
                   RECENT.TITLE,
                   RECENT.CONTENT,
                   RECENT.DATETIME,
                   RECENT.STATUS,
                   (SELECT COUNT(*) FROM T_NOTIFICATION WHERE STATUS = 0) AS UNREAD_COUNT
            FROM (
                SELECT ID, TITLE, CONTENT, DATETIME, STATUS
                FROM T_NOTIFICATION
                ORDER BY DATETIME DESC, ID DESC
            ) RECENT
            WHERE ROWNUM <= 5;
    END GET_STATE;

    PROCEDURE MARK_ALL_READ(P_UPDATED_COUNT OUT NUMBER) IS
    BEGIN
        UPDATE T_NOTIFICATION
        SET STATUS = 1
        WHERE STATUS = 0;
        P_UPDATED_COUNT := SQL%ROWCOUNT;
        COMMIT;
    END MARK_ALL_READ;
END NOTIFICATION_PKG;
